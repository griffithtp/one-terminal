#!/usr/bin/env tsx
/**
 * Generates AI-assistant adapter files from the tool-neutral sources (see .ai/README.md).
 *
 *   <dir>/AGENTS.md          →  <dir>/CLAUDE.md               (Claude Code: `@AGENTS.md` import)
 *   .ai/agents/<n>.md        →  .claude/agents/<n>.md         (Claude Code subagent)
 *   .ai/skills/<n>/SKILL.md  →  .claude/skills/<n>/SKILL.md   (Agent Skills)
 *
 * GitHub Copilot in VS Code reads these same files — AGENTS.md (root and nested),
 * .claude/agents/ and .claude/skills/ — so nothing is generated under .github/. Copies that
 * earlier versions wrote there (RETIRED_DIRS) are removed as stale.
 *
 * Generated files carry GENERATED_MARKER; a marked file with no source is stale and removed.
 * Output is formatted with the repo's Prettier config so `format:check` stays green.
 *
 * Usage:
 *   npx tsx scripts/sync-ai-config.ts           # write
 *   npx tsx scripts/sync-ai-config.ts --check   # CI: exit 1 if anything would change
 */

import { mkdir, readdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const ROOT = join(fileURLToPath(import.meta.url), "../..");
const CHECK = process.argv.includes("--check");

const SOURCE_NAME = "AGENTS.md";
const GENERATED_MARKER = "Generated by scripts/sync-ai-config.ts";
const AGENT_SOURCES_DIR = ".ai/agents";
const CLAUDE_AGENTS_DIR = ".claude/agents";
const SKILL_SOURCES_DIR = ".ai/skills";
const CLAUDE_SKILLS_DIR = ".claude/skills";

// Locations earlier versions generated for Copilot. Kept only so stale copies get removed.
const RETIRED_FILES = [".github/copilot-instructions.md"];
const RETIRED_DIRS = [".github/instructions", ".github/agents", ".github/skills"];

// `mode` in an agent's frontmatter → Claude Code's tool list. Reviewers are `read-run`:
// they read code and run checks (git diff, tests) but are told never to edit.
type Mode = "read-only" | "read-run" | "write";
const AGENT_TOOLS: Record<Mode, string> = {
  "read-only": "Read, Grep, Glob",
  "read-run": "Read, Grep, Glob, Bash",
  write: "Read, Grep, Glob, Bash, Edit, Write",
};

// Never descend into these when looking for AGENTS.md / stale CLAUDE.md files.
const SKIP_DIRS = new Set(["node_modules", "target", "dist", "gen", ".git", ".vite", "binaries"]);
const SKIP_PATHS = new Set(["packages/create-one-terminal/templates"]);

// ── Discovery ─────────────────────────────────────────────────────────────────

/** Repo-relative POSIX path, so output is identical on Windows and macOS. */
function rel(abs: string): string {
  return relative(ROOT, abs).split(sep).join("/");
}

async function walk(dir: string, found: { sources: string[]; claudeFiles: string[] }) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name) || SKIP_PATHS.has(rel(abs))) continue;
      await walk(abs, found);
    } else if (entry.name === SOURCE_NAME) {
      found.sources.push(rel(abs));
    } else if (entry.name === "CLAUDE.md") {
      found.claudeFiles.push(rel(abs));
    }
  }
}

async function readText(path: string): Promise<string | null> {
  try {
    // Git for Windows may check files out with CRLF; compare on LF.
    return (await readFile(join(ROOT, path), "utf8")).replace(/\r\n/g, "\n");
  } catch {
    return null;
  }
}

async function isGenerated(path: string): Promise<boolean> {
  return (await readText(path))?.includes(GENERATED_MARKER) ?? false;
}

async function listDir(dir: string): Promise<string[]> {
  try {
    return (await readdir(join(ROOT, dir))).map((name) => `${dir}/${name}`);
  } catch {
    return [];
  }
}

/** Every file under `dir`, recursively (repo-relative). */
async function listTree(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(join(ROOT, dir), { withFileTypes: true }).catch(() => [])) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...(await listTree(path)));
    else out.push(path);
  }
  return out;
}

// ── Rendering ─────────────────────────────────────────────────────────────────

function marker(source: string): string {
  return `<!-- ${GENERATED_MARKER} from ${source} — do not edit. Edit ${source}, then run \`npm run sync:ai\`. -->`;
}

/**
 * Re-points relative Markdown links so they still resolve once the content is copied from
 * `sourceDir` to `outputDir`. Absolute URLs, anchors and mailto links are left alone.
 */
function rebaseLinks(markdown: string, sourceDir: string, outputDir: string): string {
  if (sourceDir === outputDir) return markdown;
  return markdown.replace(/\]\(([^)\s]+)\)/g, (match, target: string) => {
    if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return match;
    const [path, anchor = ""] = target.split(/(?=#)/);
    const fromRoot = posix.normalize(posix.join(sourceDir, path));
    const rebased = posix.relative(outputDir || ".", fromRoot) || ".";
    return `](${rebased}${anchor})`;
  });
}

function renderClaudeStub(source: string): [string, string] {
  const dir = posix.dirname(source) === "." ? "" : posix.dirname(source);
  return [posix.join(dir, "CLAUDE.md"), `${marker(source)}\n\n@${SOURCE_NAME}\n`];
}

/**
 * Parses the flat `key: value` frontmatter of an agent or skill source. Kept deliberately
 * simple (no nesting, no lists) so the source format is readable by any tool or person.
 */
function parseFrontmatter(source: string, text: string, expectedName: string) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${source}: missing --- frontmatter ---`);
  const meta: Record<string, string> = {};
  for (const line of match[1].split("\n")) {
    if (!line.trim()) continue;
    const kv = /^([a-z][a-z0-9-]*):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${source}: can't parse frontmatter line "${line}"`);
    meta[kv[1]] = kv[2].replace(/^"(.*)"$/, "$1");
  }
  if (meta.name !== expectedName) {
    throw new Error(`${source}: name must be "${expectedName}" to match its file or folder`);
  }
  if (!meta.description) throw new Error(`${source}: description is required`);
  return { meta, body: match[2].trimStart() };
}

async function renderAgent(source: string): Promise<[string, string]> {
  const { meta, body } = parseFrontmatter(
    source,
    (await readText(source)) ?? "",
    posix.basename(source, ".md")
  );
  if (!(meta.mode in AGENT_TOOLS)) {
    throw new Error(`${source}: mode must be one of ${Object.keys(AGENT_TOOLS).join(", ")}`);
  }
  const front = [
    `name: ${meta.name}`,
    `description: ${JSON.stringify(meta.description)}`,
    `tools: ${AGENT_TOOLS[meta.mode as Mode]}`,
  ];
  if (meta["claude-model"]) front.push(`model: ${meta["claude-model"]}`);
  return [
    `${CLAUDE_AGENTS_DIR}/${meta.name}.md`,
    `---\n${front.join("\n")}\n---\n\n${marker(source)}\n\n${rebaseLinks(body, AGENT_SOURCES_DIR, CLAUDE_AGENTS_DIR)}`,
  ];
}

/** Skills use the Agent Skills format (`<name>/SKILL.md` with `name` + `description`). */
async function renderSkill(source: string): Promise<[string, string]> {
  const dir = posix.dirname(source);
  const name = posix.basename(dir);
  const extra = (await listDir(dir)).filter((p) => p !== source);
  if (extra.length > 0) {
    throw new Error(`${dir}: only SKILL.md is supported (found ${extra.join(", ")})`);
  }
  const { meta, body } = parseFrontmatter(source, (await readText(source)) ?? "", name);
  const outDir = `${CLAUDE_SKILLS_DIR}/${name}`;
  const front = `name: ${meta.name}\ndescription: ${JSON.stringify(meta.description)}`;
  return [
    `${outDir}/SKILL.md`,
    `---\n${front}\n---\n\n${marker(source)}\n\n${rebaseLinks(body, dir, outDir)}`,
  ];
}

async function format(path: string, content: string): Promise<string> {
  const abs = join(ROOT, path);
  const options = (await prettier.resolveConfig(abs)) ?? {};
  return prettier.format(content, { ...options, filepath: abs });
}

// ── Main ──────────────────────────────────────────────────────────────────────

const found = { sources: [] as string[], claudeFiles: [] as string[] };
await walk(ROOT, found);
found.sources.sort();

const agentSources = (await listDir(AGENT_SOURCES_DIR)).filter((p) => p.endsWith(".md")).sort();
const skillSources = (await listDir(SKILL_SOURCES_DIR)).map((dir) => `${dir}/SKILL.md`).sort();
const allSources = [...found.sources, ...agentSources, ...skillSources];

const rendered: Array<[string, string]> = [
  ...found.sources.map(renderClaudeStub),
  ...(await Promise.all(agentSources.map(renderAgent))),
  ...(await Promise.all(skillSources.map(renderSkill))),
];
const expected = new Map<string, string>();
for (const [path, content] of rendered) expected.set(path, await format(path, content));

// Previously generated files whose source has gone away, or whose location is retired.
const candidates = [
  ...found.claudeFiles,
  ...(await listDir(CLAUDE_AGENTS_DIR)),
  ...(await listDir(CLAUDE_SKILLS_DIR)).map((dir) => `${dir}/SKILL.md`),
  ...RETIRED_FILES,
  ...(await Promise.all(RETIRED_DIRS.map(listTree))).flat(),
];
const stale: string[] = [];
for (const path of candidates) {
  if (!expected.has(path) && (await isGenerated(path))) stale.push(path);
}

const changed: string[] = [];
for (const [path, content] of expected) {
  const current = await readText(path);
  if (current === content) continue;
  // Refuse to clobber a hand-written file that predates the generator.
  if (current !== null && !current.includes(GENERATED_MARKER) && !CHECK) {
    console.error(
      `✗ ${path} exists and was not generated by this script. Move its content into the ` +
        `matching ${SOURCE_NAME}, ${AGENT_SOURCES_DIR}/ or ${SKILL_SOURCES_DIR}/ file, delete it, and re-run.`
    );
    process.exit(1);
  }
  changed.push(path);
  if (!CHECK) {
    await mkdir(dirname(join(ROOT, path)), { recursive: true });
    await writeFile(join(ROOT, path), content, "utf8");
  }
}

if (!CHECK) {
  for (const path of stale) {
    await rm(join(ROOT, path));
    // Drop folders left empty: a skill's own folder, or a retired output directory.
    for (let dir = dirname(join(ROOT, path)); rel(dir).includes("/"); dir = dirname(dir)) {
      if (
        await rmdir(dir).then(
          () => false,
          () => true
        )
      )
        break;
    }
  }
}

const sourcesList = allSources.map((s) => `  ${s}`).join("\n");
if (CHECK) {
  if (changed.length || stale.length) {
    console.error("AI assistant config is out of sync with its sources:\n");
    for (const path of changed) console.error(`  out of date: ${path}`);
    for (const path of stale) console.error(`  stale:       ${path}`);
    console.error("\nTo fix, run: npm run sync:ai");
    process.exit(1);
  }
  console.log(`✓ AI assistant config is in sync (${allSources.length} sources):\n${sourcesList}`);
} else {
  for (const path of changed) console.log(`  wrote   ${path}`);
  for (const path of stale) console.log(`  removed ${path}`);
  console.log(
    `Done. ${allSources.length} sources, ${changed.length} written, ${stale.length} removed.`
  );
}
