// Bundles src/index.ts into fdc3-plugin.js, which is committed so that Rust's
// include_str!, the sample servers and scaffolded workspaces can use the plugin
// without a JS build. `--check` fails if the committed bundle is out of date.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const outfile = join(root, "fdc3-plugin.js");

const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  bundle: true,
  format: "esm",
  target: "es2020",
  minify: true,
  legalComments: "none",
  write: false,
  banner: {
    js: "// Generated by packages/fdc3-plugin/build.mjs from src/. Do not edit.",
  },
});
const code = result.outputFiles[0].text;

if (process.argv.includes("--check")) {
  if (readFileSync(outfile, "utf8") !== code) {
    console.error("fdc3-plugin.js is out of date: run `npm run build:fdc3-plugin`.");
    process.exit(1);
  }
} else {
  writeFileSync(outfile, code);
  console.log(`fdc3-plugin.js: ${(code.length / 1024).toFixed(1)} KB`);
}
